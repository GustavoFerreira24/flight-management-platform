package isep.aisafe.flightplan.importer.dsl;

import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

class FlightPlanDslSyntaxValidatorTest {

    private final FlightPlanDslSyntaxValidator validator = new FlightPlanDslSyntaxValidator();

    @Test
    void ensureValidFlightPlanProducesInternalRepresentation() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  aircraft CS-TXA;
                  pilot pilot01;
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0) altitude [1000,2000] m width 10 km wind 90 deg 12 m/s;
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertTrue(result.isValid());
        assertNotNull(result.parseTree());
        assertNotNull(result.flightPlan());
        assertEquals("TP123", result.flightPlan().identifier());
        assertEquals("REGULAR", result.flightPlan().type());
        assertEquals("CS-TXA", result.flightPlan().aircraftRegistration().orElseThrow());
        assertEquals("pilot01", result.flightPlan().pilotIdentifier().orElseThrow());
        assertEquals(1, result.flightPlan().legs().size());
        assertEquals("OPO", result.flightPlan().legs().getFirst().departure().airportCode());
        assertEquals("LIS", result.flightPlan().legs().getFirst().arrival().airportCode());
    }

    /**
     * Purpose: verify that comments and whitespace are ignored by the lexer.
     * Scenario: parse a valid flight plan containing line comments, block comments, and irregular spacing.
     * Expected output: the source is accepted as a valid Core Flight DSL file.
     */
    @Test
    void ensureCommentsAndWhitespaceAreIgnored() {
        // Arrange
        final String source = """
                // Flight generated by an external planning tool.
                flight   TP123   regular   {
                  /* Direct OPO-LIS leg. */
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0);
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertTrue(result.isValid());
    }

    /**
     * Purpose: verify that Core Flight DSL keywords are case-insensitive.
     * Scenario: parse a valid flight plan using mixed-case reserved words.
     * Expected output: the source is accepted as a valid Core Flight DSL file.
     */
    @Test
    void ensureKeywordsAreCaseInsensitive() {
        // Arrange
        final String source = """
                Flight TP123 Regular {
                  Leg {
                    Departure OPO At 2026-05-10T10:00;
                    Arrival LIS At 2026-05-10T11:00;
                    Route OPO -> LIS;
                    Segment (41.0,-8.0) -> (38.0,-9.0);
                    Fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertTrue(result.isValid());
    }

    /**
     * Purpose: verify that only formally specified units are accepted by the syntax layer.
     * Scenario: parse a flight plan with an unknown fuel unit.
     * Expected output: the source is rejected before semantic processing.
     */
    @Test
    void ensureUnknownUnitsAreRejectedBySyntaxValidation() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  aircraft CS-TXA;
                  pilot pilot01;
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0);
                    fuel 5000 banana;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertEquals(FlightPlanDslErrorType.SYNTACTIC, result.errors().getFirst().type());
    }

    /**
     * Purpose: verify that invalid characters are reported as lexical errors.
     * Scenario: parse a flight plan containing a character not defined by the lexer.
     * Expected output: the source is rejected with a lexical error containing source location.
     */
    @Test
    void ensureLexicalErrorsAreReportedWithLocation() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  aircraft CS-TXA;
                  pilot pilot01;
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0) @;
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertEquals(FlightPlanDslErrorType.LEXICAL, result.errors().getFirst().type());
        assertTrue(result.errors().getFirst().line() > 0);
        assertTrue(result.errors().getFirst().column() >= 0);
    }

    @Test
    void ensureSyntaxErrorsAreReportedWithLocation() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  leg {
                    departure OPO at 2026-05-10T10:00
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0);
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertEquals(FlightPlanDslErrorType.SYNTACTIC, result.errors().getFirst().type());
        assertTrue(result.errors().getFirst().line() > 0);
        assertTrue(result.errors().getFirst().column() >= 0);
    }

    @Test
    void ensureSemanticErrorsAreCollectedInSingleRun() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T09:00;
                    route LIS -> OPO;
                    segment (41.0,-8.0) -> (41.0,-8.0) altitude [-100,50] m width 0 km wind 360 deg -1 m/s;
                    fuel -1 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertTrue(result.errors().size() >= 6);
        assertEquals(List.of(FlightPlanDslErrorType.SEMANTIC), result.errors().stream().map(FlightPlanDslError::type).distinct().toList());
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Fuel quantity")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Segment start and end")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Route origin")));
    }

    /**
     * Purpose: verify semantic validation of the flight designator.
     * Scenario: parse a syntactically valid flight plan with an identifier that does not match the airline designator format.
     * Expected output: the source is rejected with a semantic error for the flight designator.
     */
    @Test
    void ensureInvalidFlightDesignatorIsRejectedSemantically() {
        // Arrange
        final String source = """
                flight TAP_123 regular {
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0);
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertEquals(List.of(FlightPlanDslErrorType.SEMANTIC), result.errors().stream().map(FlightPlanDslError::type).distinct().toList());
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Flight designator")));
    }

    /**
     * Purpose: verify semantic validation of optional aircraft and pilot metadata.
     * Scenario: parse a flight plan with duplicated metadata and invalid aircraft/pilot identifiers.
     * Expected output: all metadata errors are collected in a single semantic validation run.
     */
    @Test
    void ensureAircraftAndPilotMetadataAreValidatedSemantically() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  aircraft A;
                  aircraft CS-TXA;
                  pilot ab;
                  pilot pilot01;
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0);
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertEquals(List.of(FlightPlanDslErrorType.SEMANTIC), result.errors().stream().map(FlightPlanDslError::type).distinct().toList());
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Aircraft registration")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Pilot identifier")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("at most one aircraft")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("at most one pilot")));
    }

    @Test
    void ensureLegSequenceCoherenceIsValidated() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0);
                    fuel 5000 kg;
                  }
                  leg {
                    departure MAD at 2026-05-10T10:30;
                    arrival CDG at 2026-05-10T12:30;
                    route MAD -> CDG;
                    segment (40.0,-3.0) -> (49.0,2.0);
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("following leg")));
    }

    @Test
    void ensureCoordinatesAreValidatedSemantically() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (91.0,-181.0) -> (38.0,-9.0);
                    fuel 5000 kg;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Latitude")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Longitude")));
    }

    @Test
    void ensureUnitsAreValidatedByContextSemantically() {
        // Arrange
        final String source = """
                flight TP123 regular {
                  leg {
                    departure OPO at 2026-05-10T10:00;
                    arrival LIS at 2026-05-10T11:00;
                    route OPO -> LIS;
                    segment (41.0,-8.0) -> (38.0,-9.0) altitude [1000,2000] kg width 10 kg wind 90 deg 12 ft;
                    fuel 5000 m;
                  }
                }
                """;

        // Act
        final FlightPlanParseResult result = validator.validate(source);

        // Assert
        assertFalse(result.isValid());
        assertEquals(List.of(FlightPlanDslErrorType.SEMANTIC), result.errors().stream().map(FlightPlanDslError::type).distinct().toList());
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Altitude unit")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("width unit")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Wind speed unit")));
        assertTrue(result.errors().stream().anyMatch(error -> error.message().contains("Fuel unit")));
    }
}
